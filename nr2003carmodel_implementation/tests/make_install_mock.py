#!/usr/bin/env python3
"""Generate tests/install_mock.luau: executes studio/INSTALL_CARMODEL.lua and studio/ROLLBACK_CARMODEL.lua against the
mock Studio DataModel of install_mock_body.luau (a published Stage 13 bench: NR2003Client / NR2003Server sources of the
Stage 13 commit, the real Core.CupTune / TestTune / MathUtil). Run tools/build_carmodel.py first.
usage: python3 make_install_mock.py [<package dir>]   (with a converted package: also runs its
studio/INSTALL_CARMODEL_ASSETS.lua on a mock import; the generated file then embeds model data: keep it private)"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
IMPL = HERE.parent
ROOT = IMPL.parent
sys.path.insert(0, str(IMPL / "tools"))
import build_carmodel as B  # noqa: E402


def ls(text):
    eq = "="
    while ("]" + eq + "]") in text:
        eq += "="
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def main():
    rd = lambda p: p.read_text(encoding="utf-8")
    out = ["-- GENERATED by nr2003carmodel_implementation/tests/make_install_mock.py; do not edit.\n"]
    out.append("local INSTALL = %s\n" % ls(rd(IMPL / "studio" / "INSTALL_CARMODEL.lua")))
    out.append("local ROLLBACK = %s\n" % ls(rd(IMPL / "studio" / "ROLLBACK_CARMODEL.lua")))
    out.append("local PUBLISHED = {Client = %s, Server = %s}\n" % (ls(B.published("roblox/Client.client.lua")),
                                                                ls(B.published("roblox/Server.server.lua"))))
    mods = ",\n".join("\t[%r] = %s" % (m, ls(rd(IMPL / "roblox" / "CarModel" / (m + ".lua")))) for m in B.MODULES)
    out.append("local NEW = {Client = %s, Server = %s, modules = {\n%s}}\n" % (
        ls(rd(IMPL / "roblox" / "Bench" / "Client.client.lua")), ls(rd(IMPL / "roblox" / "Bench" / "Server.server.lua")), mods))
    core = ",\n".join("\t[%r] = %s" % (m, ls(rd(ROOT / "core" / (m + ".lua")))) for m in ("MathUtil", "TestTune", "CupTune"))
    out.append("local CORE = {\n%s}\n" % core)
    assets = Path(sys.argv[1]) / "studio" / "INSTALL_CARMODEL_ASSETS.lua" if len(sys.argv) > 1 else None
    out.append("local ASSETS = %s\n" % (ls(rd(assets)) if assets else "nil"))
    out.append(rd(HERE / "install_mock_body.luau"))
    (HERE / "install_mock.luau").write_text("".join(out), encoding="utf-8", newline="\n")
    print("written", HERE / "install_mock.luau")


if __name__ == "__main__":
    main()
