#!/usr/bin/env python3
"""Generate tests/carmodel_run.luau: runs the REAL roblox/CarModel/*.lua modules (loaded with a minimal Roblox API mock)
in the Luau CLI against fixtures_carmodel.lua (golden vectors of the ORIGINAL NR2003.exe / rendserv.dll code,
recovery/gen_fixtures.py).

usage: python3 make_carmodel_tests.py [<package dir>]
  <package dir> = convert_car.py output. When given, its descriptor module (luau/NR2003CarModelData_make_a.lua) is
  embedded so the rig is checked node by node; the generated file then contains data derived from the original model
  and must not be distributed (tests/.gitignore keeps it out of git). Without it the rig section is skipped."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
MODULES = ["NR2003Scale", "NR2003Gauges", "NR2003DrawState", "NR2003CameraSystem", "NR2003CarModelRig",
           "NR2003CarModelServer", "NR2003CarModelClient", "NR2003CarModelGolden", "NR2003CarModelSelfTest"]


def long_string(text):
    eq = "="
    while ("]" + eq + "]") in text:
        eq += "="
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def main():
    parts = ["-- GENERATED by nr2003carmodel_implementation/tests/make_carmodel_tests.py; do not edit.\n",
             "local SOURCES = {}\n"]
    for m in MODULES:
        parts.append("SOURCES[%r] = %s\n" % (m, long_string((ROOT / "roblox" / "CarModel" / (m + ".lua")).read_text())))
    for m in ("MathUtil", "TestTune", "CupTune"):     # bench constants (scale, hub geometry), read-only
        parts.append("SOURCES[%r] = %s\n" % (m, long_string((ROOT.parent / "core" / (m + ".lua")).read_text())))
    desc = None
    if len(sys.argv) > 1:
        p = Path(sys.argv[1]) / "luau" / "NR2003CarModelData_make_a.lua"
        desc = p.read_text()
    parts.append("local DESCRIPTOR_SOURCE = %s\n" % (long_string(desc) if desc else "nil"))
    parts.append((HERE / "carmodel_body.luau").read_text())
    out = HERE / "carmodel_run.luau"
    out.write_text("".join(parts), newline="\n")
    print("written", out, "(descriptor embedded)" if desc else "(no descriptor: rig section skipped)")


if __name__ == "__main__":
    main()
