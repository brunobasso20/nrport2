#!/usr/bin/env python3
"""Hierarchy / transform map of a converted package (Markdown) from <out>/json/<package>.json.

usage: python3 -I hierarchy_report.py <out dir> [<package>] > CARMODEL_HIERARCHY.md
Structure only (node kinds, switch variables, LOD thresholds, frame rest transforms, roles, cameras, counts); no geometry."""
import collections
import json
import os
import sys


def main():
    out = sys.argv[1]
    pkg = sys.argv[2] if len(sys.argv) > 2 else "make_a"
    d = json.load(open(os.path.join(out, "json", pkg + ".json")))
    nodes = d["nodes"]
    kids = collections.defaultdict(list)
    for n in nodes:
        if n.get("parent") is not None:
            kids[n["parent"]].append(n)
    inst = collections.Counter(i["node"] for i in d["instances"])
    tris = {g["id"]: g["tris"] for g in d["geometries"]}
    inst_tris = collections.Counter()
    for i in d["instances"]:
        inst_tris[i["node"]] += tris[i["geometry"]]

    def total(n):
        c, g, t = 1, inst[n["id"]], inst_tris[n["id"]]
        for ch in kids[n["id"]]:
            a, b, e = total(ch)
            c, g, t = c + a, g + b, t + e
        return c, g, t

    def label(n):
        k = n["kind"]
        if k == "switch":
            return "StateSwitch `%s` %s (default %s)" % (n["variable"], [round(v, 3) for v in n["values"]], n.get("default"))
        if k == "lod":
            return "LodSwitch %s m" % [round(v, 2) for v in n["distances"]]
        if k in ("case", "level"):
            return "%s %d" % (k, n["index"])
        if k == "frame":
            s = "Transform `%s` t=%s hpr=%s" % (n.get("name") or "", [round(x, 4) for x in n.get("t", [])],
                                                [round(x, 4) for x in n.get("hpr", [])])
            if n.get("keys"):
                s += " AnimatedTransform(%s, %d keys)" % (n.get("channel"), len(n["keys"]))
            return s
        if k == "billboard":
            return "Billboard pivot=%s" % n["pivot"]
        return "%s %s" % (k, n.get("name") or "")

    p = print
    p("# %s — hierarchy and transform map (generated by pipeline/hierarchy_report.py)\n" % pkg)
    p("Source: `%s` (%s, %d bytes, SHA-256 `%s`), carMakeIdx %d, undamaged. %d nodes, %d unique geometries, "
      "%d instances, markers %s (size %s studs).\n" % (
          d["meta"]["source"]["entry"], d["meta"]["source"]["source"], d["meta"]["source"]["size"],
          d["meta"]["source"]["sha256"], d["meta"]["make"], len(nodes), len(d["geometries"]), len(d["instances"]),
          ", ".join(sorted(d["markers"])), d["markerSize"]))
    p("Transform map: node-local frames in NR2003 axes (metres, +X forward, +Y left, +Z up); child = T(t) · Rz(h) Ry(p) "
      "Rx(r); geometry vertices are local to their frame and exported in Roblox axes / studs ((x, y, z) → (−y, z, −x) / "
      "%s). Roblox CFrame of a frame = body CFrame · Scale.cframe(t, R) (NR2003Scale).\n" % d["metresPerStud"])
    p("## Top of the graph (depth 3)\n")
    p("```")

    def walk(n, dep, maxdep):
        c, g, t = total(n)
        p("  " * dep + "%d %s  [%d nodes, %d instances, %d triangles in the subtree, all branches]" % (n["id"], label(n), c, g, t))
        if dep < maxdep:
            for ch in kids[n["id"]]:
                walk(ch, dep + 1, maxdep)
    walk(nodes[0], 0, 3)
    p("```\n")
    p("## External LOD levels (first LodSwitch under cockpitView case 0)\n")
    p("| level | from (m) | nodes | instances | triangles (one level) |")
    p("|---|---|---|---|---|")
    ext = [n for n in kids[2] if n["kind"] == "lod"][0] if kids.get(2) else None
    if ext:
        for lv in kids[ext["id"]]:
            c, g, t = total(lv)
            p("| %d | %.1f | %d | %d | %d |" % (lv["index"], ext["distances"][lv["index"]], c, g, t))
    p("\n## Switch variables\n")
    p("| variable | values | switches | set by (runtime) |")
    p("|---|---|---|---|")
    setters = {"cockpitView": "camera (005662d0: 0 / 1 / 10)", "wheel_speed_0": "00565b10(|RF rate|)",
               "wheel_speed_1": "00565b10(|LF rate|)", "wheel_speed_2": "00565b10(|RR rate|)",
               "wheel_speed_3": "00565b10(|LR rate|)", "animate_driver": "0 (focus car)",
               "animate_wheel": "never bound (3do default)", "day_night": "0 (day)", "roofFlapsEnable": "car+0x15ac",
               "backfireFrame": "car+0x15b0", "windshieldEnable": "option (default on → 0)",
               "mirrorFrameEnable": "00750194 → 0", "steeringWheelEnable": "option (default on → 0)",
               "tachLightEnable": "shift light", "oilPressureLightEnable": "oil < 30 psi",
               "waterTempLightEnable": "water > 110", "fuelPressureLightEnable": "fuel < 4.5 psi"}
    sw = collections.defaultdict(list)
    for n in nodes:
        if n["kind"] == "switch":
            sw[(n["variable"], tuple(round(v, 3) for v in n["values"]))].append(n["id"])
    for (var, vals), ids in sorted(sw.items()):
        p("| `%s` | %s | %d | %s |" % (var, list(vals), len(ids), setters.get(var, "")))
    p("\n## Roles (named frames driven at draw time)\n")
    p("| role | node ids | rest t (m) | rest hpr (rad) | override |")
    p("|---|---|---|---|---|")
    over = {"lfwheel": "z = car+0x1558, (steer + π/2, rest r, spin)", "rfwheel": "z = car+0x155c, (steer + π/2, rest r, spin)",
            "lrwheel": "z = car+0x1560, (rest h + π/2, rest r, spin)", "rrwheel": "z = car+0x1564, (rest h + π/2, rest r, spin)",
            "steer": "(rest h, rest p, wheel angle) — cockpit", "shifter": "(rest h, car+0x1588, car+0x158c) — cockpit",
            "head": "t = head; (0, headPitch − p, headRoll − r)", "ptach": "(0, rest p, 0056f040(rpm))",
            "poilp": "(0, rest p, oil pressure)", "poilt": "(0, rest p, car+0x1520)", "pfuel": "(0, rest p, fuel pressure)",
            "pwater": "(0, rest p, car+0x1524)", "pvoltage": "(0, rest p, voltage)"}
    for role, ids in sorted(d["roles"].items()):
        n = nodes[ids[0]]
        p("| `%s` | %s | %s | %s | %s |" % (role, ", ".join(map(str, ids[:6])) + (" …" if len(ids) > 6 else ""),
                                           [round(x, 4) for x in n.get("t", n.get("pivot", []))],
                                           [round(x, 4) for x in n.get("hpr", [])], over.get(role, "AnimatedTransform (timeValue)" if n.get("keys") else "")))
    p("\n## On-car cameras (`%s.cam`, chunk MACC)\n" % d["meta"]["model"])
    p("| mode | name | pos (m, body frame) | hpr (rad) | fov triple |")
    p("|---|---|---|---|---|")
    for name, c in sorted(d["cameras"].items(), key=lambda kv: kv[1]["mode"]):
        p("| %d | %s | %s | %s | %s |" % (c["mode"], name, [round(x, 4) for x in c["pos"]], [round(x, 5) for x in c["hpr"]],
                                         [round(x, 5) for x in c["fov"]]))


if __name__ == "__main__":
    main()
