"""Widen placed-generic callbacks for the original Watkins Glen setup files.

Only extra constant-cell allocations are imposed. A shared constant cell may
become a distinct cell holding its actual value; no coefficient is substituted.
The original emitter still generates the callbacks, which are then translated.
"""
import argparse
import base64
import json
from pathlib import Path
import pickle
import re
import time
import os

import gen_placed as G

# One-based events whose former shared cells are setup/placement dependent.
# Reproduced by the retained diagnostic build of fast.cup.sim, plus the original
# emitter comparison. Sharing these cells rejected the car at placement.
EXTRA_CELLS = (85, 374, 2096, 2098, 3035, 3042, 4449, 4453, 4456, 21810, 21811, 26348)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=G.REPO / 'watkinsglen_implementation/core/NR2003Cup')
    args = parser.parse_args()
    setups = json.loads((G.REPO / 'watkinsglen_implementation/handling/setup_sources.json').read_text())
    original = (G.REPO / 'watkinsglen_implementation/core/NR2003Cup/NR2003CupTrackBuild.lua').read_text()
    fold, litf, lita = re.search(r'placedGeneric = \{fold = "([^"]+)",\s*litf = "([^"]+)",\s*lita = "([^"]+)"',original).groups()
    # Mirror the complete runtime TableControl policy, including unmarked n/0/2
    # allocations/no-folds. Imposing only the uppercase subset was insufficient
    # when changed setup values altered constant-cell sharing at placement.
    force = {({'Z':'z','0':'z','O':'o','2':'o','N':'a','n':'a'}[c],i)
             for i,c in enumerate(fold) if c in 'Z0O2Nn'}
    import struct
    addresses = struct.unpack('<'+'I'*len(litf),base64.b64decode(lita))
    owners,follow={},{}
    for i,(append,address) in enumerate(zip(litf,addresses)):
        if append=='1': follow[i]='append';owners[address]=i
        else: follow[i]=('m',owners[address])
    force |= {('a', i - 1) for i in EXTRA_CELLS}
    report, reference, base = {}, None, None
    pending=list(('default', 'fast', 'easy', 'qualify', 'jasper'))
    iterations=0
    while pending:
        name=pending.pop(0)
        started = time.monotonic()
        setup_file = None if name == 'default' else Path(os.environ['WG_TRACK'])/setups[name]['file']
        m, tables, summary = G.run('placedGeneric', force_override=force,follow_override=follow,setup_file=setup_file)
        if reference is None:
            reference = tables, summary
            base = m
        else:
            wanted, ref = reference
            # Non-forced n cells can be kept instead of reallocated in the natural
            # emitter. Runtime policy imposes allocation for all n/N entries.
            differences = [(i + 1, a, b) for i, (a, b) in enumerate(zip(wanted[0], tables[0]))
                           if a != b and a not in 'nN']
            if differences:
                for index,a,b in differences:
                    force.add(('a' if a in 'kzonN' else ('z' if a in '01Z' else 'o'),index-1))
                print('Widening',name,differences,flush=True)
                iterations+=1
                assert iterations<=8,'Placed callback policy did not converge'
                reference=None;report={};pending=list(('default','fast','easy','qualify','jasper'))
                continue
            assert wanted[1:] == tables[1:], (name, 'literal policy changed')
            assert all(summary[k] == ref[k] for k in ('codeEnd', 'litTop', 'nfold', 'nlit', 'slots')), (name, summary)
        report[name] = {**summary, 'seconds': time.monotonic() - started}
        print(name, json.dumps(report[name]), flush=True)
    tables, ref = reference
    jit,used,natives,_=G.translate(base)
    assert not natives-G.core_natives()
    args.out.mkdir(parents=True,exist_ok=True)
    files=G.emit_modules(args.out,'NR2003CupJITPG',jit,
        '-- Watkins Glen port: callbacks of the car PLACED on the track (placedGeneric structure), generated by\n'
        '-- watkinsglen_implementation/recovery/lift/gen_placed.py: the ORIGINAL in-place rebuild 00551760 ->\n'
        '-- 005b2f20 at the placed pose (005512f0), translated with recovery/stage6_7/jit2lua.py.\n')
    f, lf, la = tables
    block = 'placedGeneric = {fold = "%s",\nlitf = "%s",\nlita = "%s",\n' % (
        f, ''.join('1' if v else '0' for v in lf),
        base64.b64encode(b''.join(v.to_bytes(4, 'little') for v in la)).decode())
    block += 'ref = {pool = %d, litTop = %d, codeEnd = %d, nlit = %d, nfold = %d, slots = {%s}}},' % (
        ref['pool'], ref['litTop'], ref['codeEnd'], ref['nlit'], ref['nfold'], ', '.join(map(str, ref['slots'])))
    target = args.out / 'NR2003CupTrackBuild.lua'
    original, count = re.subn(r'placedGeneric = \{fold = ".*?slots = \{[^}]*\}\}\},', lambda _: block, original, flags=re.S)
    assert count == 1 and len(original.encode()) < 199000
    target.write_text(original)
    (G.REPO / 'watkinsglen_implementation/handling/placed_setups_report.json').write_text(
        json.dumps({'extraCellEvents': EXTRA_CELLS, 'generatedFiles': files, 'setups': report}, indent=2) + '\n')


if __name__ == '__main__':
    main()
