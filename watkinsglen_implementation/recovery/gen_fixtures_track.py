"""Regression fixtures of the Watkins Glen track world for the Luau tests (watkinsglen_implementation/tests/run_track.luau)
from the ORIGINAL code in Unicorn (ref_track.py pickles):
  fixtures/track_<scenario>.lua = {stall, frames, controls (per frame), states (45 u32 per tick: every tick of the first
  two frames, then the last tick of every frame), enter / checks (cells written by the original from the session start
  on, with their values after the placement / at the checkpoint frames)}
Usage: python3 gen_fixtures_track.py <out dir> <world_<scenario>.pkl>..."""
import sys
import base64
import pickle
import struct
from pathlib import Path

BASE = 0x6e9000
EXCLUDE = [(0xf7a000, 0xf80000), (0x6e9000, 0x6ea000)]   # host blocks / virtual stacks, import slots


def b64u32(vals):
    return base64.b64encode(struct.pack('<%dI' % len(vals), *vals)).decode()


def cells_lua(d, region=None):
    keys = [a for a in sorted(d) if not any(lo <= a < hi for lo, hi in EXCLUDE)]
    if region:
        keys = [a for a in keys if region(a)]
    return '{n=%d, addr="%s", val="%s"}' % (len(keys), b64u32(keys), b64u32([d[a] for a in keys]))


def wheel_checks(fx, snap):
    """Read the ORIGINAL per-tire outputs and callback rolling-resistance cells from written-memory checkpoints."""
    def raw(a, cells):
        aligned = a & ~3
        def cell(addr):
            if addr in cells:
                return cells[addr]
            for lo, data in snap.items():
                if lo <= addr < lo + len(data):
                    return int.from_bytes(data[addr-lo:addr-lo+4], 'little')
            raise KeyError(hex(addr))
        lo = cell(aligned)
        shift = (a - aligned) * 8
        return lo if shift == 0 else ((lo >> shift) | (cell(aligned+4) << (32-shift))) & 0xffffffff
    lines = []
    for frame, cells in sorted(fx['checks'].items()):
        wheels = []
        for w in range(4):
            tire = 0xbf3a20 + w * 0xa39
            rr = raw(0xc081f4 + 4*w, cells)
            values = [raw(tire+o, cells) for o in (0x2c0, 0x2d8, 0x2dc, 0x2e0, 0x2f0, 0x2ec, 0x2cc)]
            values.append(raw(rr, cells))
            wheels.append('{%s}' % ','.join(str(v) for v in values))
        lines.append('[%d]={%s}' % (frame, ','.join(wheels)))
    return ',\n'.join(lines)


def write_surface_fixture(out, snap):
    tables = [('loadedGrip', 0x74fb30, 20), ('contactStiffness', 0x6f6148, 20),
              ('contactDamping', 0x6f6198, 20), ('rollingConstant', 0x6f63c8, 20),
              ('rollingSpeedSquared', 0x6f6418, 20), ('surfaceHeat', 0x6f65c0, 20),
              ('roughnessHeights', 0x6f41d8, 256), ('roughnessQuantization', 0x6ea514, 1),
              ('roughnessScale', 0x74c36c, 1)]
    rows = []
    for name, address, count in tables:
        for lo, data in snap.items():
            if lo <= address and address + count*4 <= lo + len(data):
                values = struct.unpack_from('<%dI' % count, data, address-lo)
                rows.append('{name="%s",address=%d,bits={%s}}' % (name, address, ','.join(str(x) for x in values)))
                break
        else:
            raise KeyError(hex(address))
    text = '-- Generated from the ORIGINAL executed track-load snapshot; float32 bit patterns.\nreturn {\n' + ',\n'.join(rows) + '\n}\n'
    (out / 'surface_tables.lua').write_text(text)


def lua_val(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return repr(float(v)) if isinstance(v, float) else str(v)


def main(out_dir, pkls):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for p in pkls:
        res = pickle.load(open(p, 'rb'))
        write_surface_fixture(out, res['snap'])
        for name, sc in res['scenarios'].items():
            fx = sc['fixture']
            st = fx['states']
            ticks = [k for k in range(len(st)) if k < 16 or k % 8 == 7]
            flat = []
            for k in ticks:
                flat += st[k]
            ctl = ['{%s}' % ', '.join('%s=%s' % (k, lua_val(v)) for k, v in sorted(c.items())) for c in fx['controls']]
            checks = ['[%d] = %s' % (f, cells_lua(c)) for f, c in sorted(fx['checks'].items())]
            src = ['-- GENERATED by watkinsglen_implementation/recovery/gen_fixtures_track.py from the ORIGINAL NR2003 code',
                   '-- (Unicorn reference orig_world.OriginalWorld, ref_track.py scenario %r); do not edit.' % name,
                   'return {name="%s", stall={%s}, frames=%d,' % (name, ', '.join(repr(float(x)) for x in fx['stall']), fx['frames']),
                   'controls={', ',\n'.join(ctl), '},',
                   'ticks={%s},' % ','.join(str(k) for k in ticks),
                   'states="%s",' % b64u32(flat),
                   '-- wheelChecks fields: surface(u32), Fx/Fy/Fz(N), vx/vslip/tread(m/s), rollingTorque(Nm), raw f32 bits',
                   'wheelChecks={%s},' % wheel_checks(fx, res['snap']),
                   'enter=%s,' % cells_lua(fx['enter']),
                   'checks={', ',\n'.join(checks), '}}']
            s = '\n'.join(src) + '\n'
            (out / ('track_%s.lua' % name)).write_text(s)
            print(name, 'bytes', len(s), 'enter cells', len(fx['enter']), 'checks',
                  {f: len(c) for f, c in fx['checks'].items()})


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
