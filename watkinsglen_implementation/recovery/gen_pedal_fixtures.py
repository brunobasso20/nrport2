"""Execute original 00552df0/005534f0 for independent pedal fixtures.

Only device/context boundaries are supplied: raw controls, option getter for TC,
timer count. The original throttle, axis, speed and clutch instructions execute.
No host implementation of either pedal supplies the expected results.
"""
import json
import os
from pathlib import Path
import random
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'recovery/stage6_7'))
from nrx import Machine

F = lambda v: struct.unpack('<f', struct.pack('<f', v))[0]
U = lambda v: struct.unpack('<I', struct.pack('<f', v))[0]
THR, BRAKE, RAW, TYPE = 5, 6, 0xd35b18, 0xd37cc8
HELP, TIMER, STUB = 0xf7f180, 0xf7f184, 0xf7f190


def main():
    m = Machine(fpcw=0x077f)
    m.uc.mem_write(0x550180, b'\xa0' + struct.pack('<I', HELP) + b'\xc3')
    m.uc.mem_write(0x5f7cd0, b'\xa1' + struct.pack('<I', TIMER) + b'\xc3')
    for offset, address, out in ((0, 0x552df0, 0xbf6390), (16, 0x5534f0, 0xbf6eb0)):
        m.uc.mem_write(STUB + offset, b'\xe8' + struct.pack('<i', address - (STUB + offset + 5)) +
                       b'\xd9\x1d' + struct.pack('<I', out) + b'\xc3')
    rng = random.Random(20261014)
    vectors = []
    # raw throttle/brake, previous pedal, binding kind, axis states/rates,
    # TC flag, gear, speed, rear slips; plus original result + written states.
    for i in range(1800):
        digital = i % 3 != 0
        help_on = i >= 1200
        values = [F(rng.choice([0, 1]) if digital else rng.random()),
                  F(rng.choice([0, 1, .49, .5, .51])), F(rng.random()), 0 if digital else 1,
                  F(rng.random()), F(rng.random()), rng.choice([1, .2, .033]), rng.choice([1, .1, .04]),
                  int(help_on), rng.choice([1, 2, 3, 4]), rng.choice([0, 5, 9.99, 10, 10.01, 20, 24.99, 25, 40]),
                  F(rng.uniform(-8, 8)), F(rng.uniform(-8, 8))]
        raw, brake, previous, kind, ts, bs, tr, br, tc, gear, velocity, sl, sr = values
        for ctl, value in ((5, raw), (6, brake)): m.wf(RAW + 10 * ctl, value)
        m.w32(TYPE + 29 * 5, kind); m.w32(TYPE + 29 * 6, 0)
        for address, value in ((0xbf6390, previous), (0xbf63a4, ts), (0xbf63a8, bs),
                               (0x74c994, tr), (0x74c998, br), (0xbf6d44, velocity),
                               (0xbf6d4c, 0), (0xbf6d54, 0), (0xbf513e, sl), (0xbf5b77, sr)):
            m.wf(address, value)
        m.uc.mem_write(HELP, bytes([tc])); m.w32(TIMER, i + 1); m.w32(0x74c97c, gear)
        m.call(STUB)
        vectors.append([*[U(v) if j not in (3, 8, 9) else int(v) for j, v in enumerate(values)],
                        m.u32(0xbf6390), m.u32(0xbf63a4), m.u32(0xbf63a8), m.uc.mem_read(0xbf6eba, 1)[0]])
    clutch = []
    for mode in [0, 1, 2]:
        for wheel in [0, 1, 14.66, 14.67, 20, -20]:
            for throttle in [0, .1, .2, .3, 1]:
                for raw in [0, .3, 1]:
                    m.w32(0x74c974, mode); m.wf(0xbf6d88, wheel)
                    m.wf(0xbf6390, throttle); m.wf(RAW + 40, raw)
                    m.call(STUB + 16)
                    clutch.append([mode, U(wheel), U(throttle), U(raw), m.u32(0xbf6eb0)])
    out = ROOT / 'watkinsglen_implementation/handling/tests/pedal_fixtures.lua'
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ['-- ORIGINAL x86 pedal functions; generated by recovery/gen_pedal_fixtures.py.',
             'return {throttle={']
    lines += ['{' + ','.join(map(str, v)) + '},' for v in vectors]
    lines += ['},clutch={'] + ['{' + ','.join(map(str, v)) + '},' for v in clutch] + ['}}', '']
    out.write_text('\n'.join(lines))
    print(json.dumps({'originalThrottleVectors': len(vectors), 'originalClutchVectors': len(clutch)}))


if __name__ == '__main__':
    main()
