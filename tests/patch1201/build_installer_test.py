"""Embed the actual generated Studio installer and baselines in its Luau mock.

python tests/patch1201/build_installer_test.py --studio-prediction /path/to/extracted/script-137.lua
luau -O2 --codegen tests/patch1201/run_installer.luau
"""
import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
BASELINE = "e949f5db1a58508999721cd8bca75c8af20408c4"


def literal(text):
    equals = "="
    while "]" + equals + "]" in text:
        equals += "="
    return "[" + equals + "[\n" + text + "]" + equals + "]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--studio-prediction", type=Path, required=True)
    args = parser.parse_args()
    old = lambda path: subprocess.check_output(["git", "show", f"{BASELINE}:{path}"], cwd=ROOT).decode()
    texts = {
        "APPLY": (ROOT / "PATCH_NR2003_1201_SETUPS.lua").read_text(),
        "ROLLBACK": (ROOT / "PATCH_NR2003_1201_SETUPS_ROLLBACK.lua").read_text(),
        "OLD_SETUP": old("roblox/NR2003WatkinsGlenSetup.lua"),
        "OLD_PREDICTION": args.studio_prediction.read_text(),
        "OLD_LEGACY": old("roblox/Server.server.lua"),
        "NEW_SETUP": (ROOT / "roblox/NR2003WatkinsGlenSetup.lua").read_text(),
        "NEW_CONTROLS": (ROOT / "roblox/SetupTestControls.lua").read_text(),
        "NEW_BINDINGS": (ROOT / "roblox/SetupTestBindings.client.lua").read_text(),
        "NEW_PREDICTION": (ROOT / "roblox/PredictionServer.lua").read_text(),
        "NEW_LEGACY": (ROOT / "roblox/Server.server.lua").read_text(),
    }
    out = ["-- GENERATED by tests/patch1201/build_installer_test.py; actual installer and independently retained old sources."]
    out += ["local " + name + " = " + literal(text) for name, text in texts.items()]
    out += [(ROOT / "tests/patch1201/installer_mock_body.luau").read_text()]
    (ROOT / "tests/patch1201/run_installer.luau").write_text("\n".join(out))


if __name__ == "__main__":
    main()
