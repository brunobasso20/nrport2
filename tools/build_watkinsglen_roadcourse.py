#!/usr/bin/env python3
"""Package the road-course V6 correction on top of either shipped V5 install."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile
from build_watkinsglen import ROOT, fingerprint, lua, normalize

FOLDER=ROOT/'watkinsglen_implementation/roadcourse'
OUT=FOLDER/'studio'
NAME='NR2003_WatkinsGlen_RoadCourseV6'
BACKUP='NR2003Backup_WatkinsGlenRoadCourseV6'


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    full=json.loads((FOLDER/'base_v5_full_manifest.json').read_text())
    handling=json.loads((FOLDER/'base_v5_handling_manifest.json').read_text())
    targets=[];payloads={}
    for prior in full['targets']:
        source=normalize((ROOT/prior['file']).read_text())
        if fingerprint(source)==prior['new']:continue
        target={**prior,'old':prior['new'],'new':fingerprint(source)}
        targets.append(target);payloads[target['key']]=source
    added=list((ROOT/'watkinsglen_implementation/core/NR2003Cup').glob('NR2003CupJITWG*.lua'))
    added.append(ROOT/'watkinsglen_implementation/core/NR2003Cup/NR2003CupWatkinsGlenSpec.lua')
    for path in added:
        source=normalize(path.read_text());key='Core.NR2003Cup.'+path.stem
        targets.append({'key':key,'class':'ModuleScript','file':str(path.relative_to(ROOT)),'old':None,'new':fingerprint(source)})
        payloads[key]=source
    targets.sort(key=lambda t:t['key'])
    changed={t['key'] for t in targets}
    dependencies=[d for d in full['dependencies'] if d['key'] not in changed]
    dependencies += [{'key':t['key'],'class':t['class'],'accepted':[t['new']]}
                     for t in full['targets'] if t['key'] not in changed]
    templates=ROOT/'watkinsglen_implementation/studio'
    apply=(templates/'Apply.lua').read_text().replace('NR2003Backup_WatkinsGlen',BACKUP).replace('NR2003_WatkinsGlen_InstallV5',NAME)
    apply=apply.replace('Watkins Glen V5 installed: original track setups/pedals and per-wheel track HUD;',
                        'Watkins Glen V6 installed: road-course chassis 4, original tire profile 8 and track HUD;')
    marker='    local storage = game:GetService("ServerStorage")\n'
    guard='''    local older = storage:FindFirstChild("NR2003Backup_WatkinsGlenHandlingV5")
    local baseManifest = older and require(install.BaseHandlingManifest) or require(install.BaseManifest)
    older = older or H.child(storage, "NR2003Backup_WatkinsGlen")
    assert(older.ClassName == "Folder" and older:GetAttribute("Complete") == true and
        older:GetAttribute("Bundle") == baseManifest.bundle, "V6 requires the complete retained V5 backup")
    H.backupEntries(older, baseManifest)
    assert(pkg:GetAttribute("NR2003Track") == "watkins_glen" and
        (pkg:GetAttribute("NR2003WatkinsGlenPatch") == baseManifest.bundle or
         pkg:GetAttribute("NR2003WatkinsGlenPatch") == manifest.bundle),
        "RoadCourse V6 requires the installed V5; use the shipped V5 installer first")
'''
    assert apply.count(marker)==1;apply=apply.replace(marker,marker+guard)
    rollback=(templates/'Rollback.lua').read_text().replace('NR2003Backup_WatkinsGlen',BACKUP)
    rollback=rollback.replace('Watkins Glen patch rolled back.','Watkins Glen road-course correction rolled back to V5.')
    sources={'Apply':apply,'Support':(templates/'Support.lua').read_text(),'Rollback':rollback,
             'BaseManifest':'-- Pinned V5 full installer, data only.\nreturn '+lua(full)+'\n',
             'BaseHandlingManifest':'-- Pinned V5 updater, data only.\nreturn '+lua(handling)+'\n'}
    manifest={'schema':1,'track':'watkins_glen','metresPerStud':.28,'version':6,'previousBundles':[],
              'recoveryTargets':[],'targets':targets,'dependencies':dependencies,
              'installerSources':{n:fingerprint(s) for n,s in sources.items()}}
    manifest['bundle']=hashlib.sha256(json.dumps(manifest,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    sources['Manifest']='-- Generated by tools/build_watkinsglen_roadcourse.py.\nreturn '+lua(manifest)+'\n'
    xml=ET.Element('roblox',version='4')
    for n in ('null','nil'):ET.SubElement(xml,'External').text=n
    count=0
    def item(parent,name,cls='Folder',source=None):
        nonlocal count
        count+=1;node=ET.SubElement(parent,'Item',{'class':cls,'referent':'RBX'+str(count)})
        props=ET.SubElement(node,'Properties');ET.SubElement(props,'string',name='Name').text=name
        if source is not None:
            assert len(source.encode())<199000
            ET.SubElement(props,'ProtectedString',name='Source').text=source
        return node
    model=item(xml,NAME,'Model')
    for name,source in sources.items():item(model,name,'ModuleScript',source)
    tree={'':item(model,'Sources')}
    for key,source in sorted(payloads.items()):
        parts=key.split('.')
        for i in range(1,len(parts)):
            path='.'.join(parts[:i])
            if path not in tree:tree[path]=item(tree['.'.join(parts[:i-1])],parts[i-1])
        item(tree['.'.join(parts[:-1])],parts[-1],'ModuleScript',source)
    ET.indent(xml,space='  ')
    (OUT/(NAME+'.rbxmx')).write_bytes(ET.tostring(xml,encoding='utf-8',xml_declaration=True))
    for name,source in sources.items():(OUT/(name+'.lua')).write_text(source)
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (OUT/'APPLY_ROADCOURSE_V6.lua').write_text('-- Outside Play; insert '+NAME+'.rbxmx into Workspace.\nrequire(workspace.'+NAME+'.Apply)()\n')
    (OUT/'ROLLBACK_ROADCOURSE_V6.lua').write_text('-- Outside Play; restore V5 and retain its backups.\nrequire(game.ServerStorage.'+BACKUP+'.Rollback)()\n')
    archive=ROOT/'watkinsglen_implementation/downloads/WatkinsGlen_RoadCourse_Patch_V6.zip'
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for n in (NAME+'.rbxmx','APPLY_ROADCOURSE_V6.lua','ROLLBACK_ROADCOURSE_V6.lua'):z.write(OUT/n,n)
        for n in ('README.md','VALIDATION.md'):
            if (FOLDER/n).exists():z.write(FOLDER/n,n)
        for log in sorted((FOLDER/'validation').glob('*.log')):
            if log.name != 'package.log':z.write(log,'validation/'+log.name)
    with zipfile.ZipFile(archive) as z:assert z.testzip() is None
    print(json.dumps({'bundle':manifest['bundle'],'targets':len(targets),'checks':len(dependencies),'zipBytes':archive.stat().st_size,'model':NAME},indent=2))


if __name__=='__main__':main()
