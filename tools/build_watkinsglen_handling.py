#!/usr/bin/env python3
"""Package a transactional V4 -> V5 update using the tested full installer.

The V4 backup remains intact. This update has its own backup and rollback;
rolling it back restores V4 before the original V4 rollback can be used.
"""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

from build_watkinsglen import ROOT, fingerprint, lua, normalize

OUT=ROOT/'watkinsglen_implementation/handling/studio'
NAME='NR2003_WatkinsGlen_HandlingV5'
BACKUP='NR2003Backup_WatkinsGlenHandlingV5'


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    base=json.loads((OUT.parent/'base_v4_manifest.json').read_text())
    final=json.loads((ROOT/'watkinsglen_implementation/studio/manifest.json').read_text())
    old={t['key']:t for t in base['targets']}
    targets=[];payloads={}
    for item in final['targets']:
        prior=old.get(item['key'])
        if prior and item['new']==prior['new']:continue
        target={**item,'old':prior['new'] if prior else item['old']}
        targets.append(target)
        source=normalize((ROOT/item['file']).read_text())
        assert fingerprint(source)==target['new']
        payloads[item['key']]=source
    changed={t['key'] for t in targets}
    dependencies=[d for d in base['dependencies'] if d['key'] not in changed]
    dependencies += [{'key':t['key'],'class':t['class'],'accepted':[t['new']]}
                     for t in base['targets'] if t['key'] not in changed]
    base_lua='-- Pinned installed V4 metadata; data only.\nreturn '+lua(base)+'\n'
    full=ROOT/'watkinsglen_implementation/studio'
    apply=(full/'Apply.lua').read_text().replace('NR2003Backup_WatkinsGlen',BACKUP).replace(
        'NR2003_WatkinsGlen_InstallV5',NAME)
    marker='    local storage = game:GetService("ServerStorage")\n'
    assert apply.count(marker)==1
    guard='''    assert(pkg:GetAttribute("NR2003Track") == "watkins_glen" and
        (pkg:GetAttribute("NR2003WatkinsGlenPatch") == manifest.baseBundle or
         pkg:GetAttribute("NR2003WatkinsGlenPatch") == manifest.bundle),
        "Handling V5 requires the installed Watkins Glen V4 patch; use the full V5 installer for a fresh place")
    local baseBackup = H.child(storage, "NR2003Backup_WatkinsGlen")
    assert(baseBackup.ClassName == "Folder" and baseBackup:GetAttribute("Complete") == true and
        baseBackup:GetAttribute("Bundle") == manifest.baseBundle, "The original complete V4 backup must be retained")
    H.backupEntries(baseBackup, require(install.BaseManifest))
'''
    apply=apply.replace(marker,marker+guard)
    rollback=(full/'Rollback.lua').read_text().replace('NR2003Backup_WatkinsGlen',BACKUP)
    rollback=rollback.replace('Watkins Glen patch rolled back.','Watkins Glen handling update rolled back to V4.')
    sources={'Apply':apply,'Support':(full/'Support.lua').read_text(),'Rollback':rollback,'BaseManifest':base_lua}
    manifest={'schema':1,'track':'watkins_glen','metresPerStud':.28,'version':5,'baseBundle':base['bundle'],
              'previousBundles':[],'recoveryTargets':[],'targets':targets,'dependencies':dependencies,
              'installerSources':{n:fingerprint(s) for n,s in sources.items()}}
    manifest['bundle']=hashlib.sha256(json.dumps(manifest,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    sources['Manifest']='-- Generated by tools/build_watkinsglen_handling.py.\nreturn '+lua(manifest)+'\n'
    xml=ET.Element('roblox',version='4')
    for name in ('null','nil'):ET.SubElement(xml,'External').text=name
    count=0
    def item(parent,name,cls='Folder',source=None):
        nonlocal count
        count+=1
        node=ET.SubElement(parent,'Item',{'class':cls,'referent':'RBX'+str(count)})
        props=ET.SubElement(node,'Properties');ET.SubElement(props,'string',name='Name').text=name
        if source is not None:
            assert len(source.encode())<199000
            ET.SubElement(props,'ProtectedString',name='Source').text=source
        return node
    model=item(xml,NAME,'Model')
    for name,source in sources.items():item(model,name,'ModuleScript',source)
    tree={'':item(model,'Sources')}
    for key,source in sorted(payloads.items()):
        parts=key.split('.')
        for i in range(1,len(parts)):
            path='.'.join(parts[:i])
            if path not in tree:tree[path]=item(tree['.'.join(parts[:i-1])],parts[i-1])
        item(tree['.'.join(parts[:-1])],parts[-1],'ModuleScript',source)
    ET.indent(xml,space='  ')
    (OUT/(NAME+'.rbxmx')).write_bytes(ET.tostring(xml,encoding='utf-8',xml_declaration=True))
    for name,source in sources.items():(OUT/(name+'.lua')).write_text(source)
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (OUT/'APPLY_HANDLING_V5.lua').write_text('-- Outside Play, after inserting '+NAME+'.rbxmx into Workspace.\nrequire(workspace.'+NAME+'.Apply)()\n')
    (OUT/'ROLLBACK_HANDLING_V5.lua').write_text('-- Outside Play; restore V4 without removing its track/car installation.\nrequire(game.ServerStorage.'+BACKUP+'.Rollback)()\n')
    archive=ROOT/'watkinsglen_implementation/downloads/WatkinsGlen_Handling_Patch_V5.zip'
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for name in (NAME+'.rbxmx','APPLY_HANDLING_V5.lua','ROLLBACK_HANDLING_V5.lua'):z.write(OUT/name,name)
        z.write(OUT.parent/'README.md','LEIA_PRIMEIRO.md')
        z.write(OUT.parent/'VALIDATION.md','VALIDATION.md')
        for log in sorted((OUT.parent/'validation').glob('*.log')):
            if log.name != 'package.log':z.write(log,'validation/'+log.name)
    with zipfile.ZipFile(archive) as z:assert z.testzip() is None
    print(json.dumps({'bundle':manifest['bundle'],'targets':len(targets),'checks':len(dependencies),
                      'zipBytes':archive.stat().st_size,'model':NAME},indent=2))


if __name__=='__main__':main()
