#!/usr/bin/env python3
"""Recover original STGP setup chunks without snapping their stored values.

00558830 serializes only items with a toInternal descriptor. The original
006ed7f0 version table ends version 13 at item 68 and version 14 at item 70.
00558da0 validates loaded values by clamping, without the UI step snapping.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]


def recover(path, descriptors):
    raw = path.read_bytes()
    assert raw[:12] == struct.pack('<4sII', b'PGTS', 5, len(raw) - 12)
    # Only decode the setup-value chunk; the header/name and note chunks have
    # version-dependent layouts and are not physics inputs.
    assert raw.count(b'DGTS') == 1
    at = raw.index(b'DGTS')
    version, size = struct.unpack_from('<II', raw, at + 4)
    data = raw[at + 12:at + 12 + size]
    assert len(data) == size and raw[at + 12 + size:at + 16 + size] == b'TGTS'
    last = {13: 68, 14: 70}[version]
    fields = [i for i in range(last + 1) if i in descriptors]
    assert len(data) == 4 * len(fields)
    values = dict(zip(fields, struct.unpack('<' + 'I' * len(fields), data)))
    return {'file': path.name, 'sha256': hashlib.sha256(raw).hexdigest(),
            'version': version, 'lastItem': last, 'values': values}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--track', type=Path, default=ROOT / 'work/tracks/watkins_glen')
    args = parser.parse_args()
    descriptors = set()
    for line in (ROOT / 'core/NR2003Cup/NR2003CupSetupData.lua').read_text().splitlines():
        match = re.match(r'\[(\d+)\]=\{', line)
        if match and 'toInternal=nil' not in line:
            descriptors.add(int(match[1]))
    sets = {name: recover(args.track / (name + '.cup.sim'), descriptors)
            for name in ('fast', 'easy', 'qualify', 'jasper')}
    out = ['-- Generated by tools/build_watkinsglen_setups.py from the supplied original .sim files.',
           '-- Raw setup values; retain file values between garage UI steps.', 'local DATA = {']
    for name, setup in sets.items():
        values = ','.join('[%d]=0x%08x' % (i, v) for i, v in setup['values'].items())
        out.append('    %s = {file=%s,sha256=%s,items={%s}},' %
                   (name, json.dumps(setup['file']), json.dumps(setup['sha256']), values))
    out += ['}', 'local M = {}', 'function M.new(Setup, name)',
            '    name = name or "fast"',
            '    local data = assert(DATA[name], "WatkinsGlenSetup must be fast, easy, qualify or jasper")',
            '    local items = Setup.defaults()',
            '    for i, raw in pairs(data.items) do items[i] = raw end',
            '    assert(Setup.validateLoaded(items), "Original Watkins Glen setup validation failed")',
            '    return items, name, data.sha256', 'end', 'return M', '']
    (ROOT / 'roblox/NR2003WatkinsGlenSetup.lua').write_text('\n'.join(out))
    report = ROOT / 'watkinsglen_implementation/handling/setup_sources.json'
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(sets, indent=2) + '\n')
    print('Recovered original setup fields:', {k: len(v['values']) for k, v in sets.items()})


if __name__ == '__main__':
    main()
