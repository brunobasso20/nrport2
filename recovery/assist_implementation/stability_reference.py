"""Original 00561e50 aid-on/off chassis forces for synthetic body velocities."""
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "recovery/stage10"), str(ROOT / "recovery/stage6_7")]
import orig_setup as O

TABLE, OUT = 0xF7E200, 0xF7E300


def bits(value): return struct.unpack("<I", struct.pack("<f", value))[0]
def lua(value):
    if isinstance(value, dict): return "{" + ",".join("[" + json.dumps(k) + "]=" + lua(v) for k, v in value.items()) + "}"
    if isinstance(value, list): return "{" + ",".join(map(lua, value)) + "}"
    if isinstance(value, str): return json.dumps(value)
    return repr(value)


def main():
    m = O.boot()
    O.prepare(m)
    O.apply(m)
    m.uc.mem_write(O.BG_FLAG, b"\x01")
    coefficients = list(range(0x74DECC, 0x74DF10, 4)) + [0xC086A4, 0xC086A8]
    result = {"source": "NR2003 1.2.0.1 ORIGINAL 00561e50 in Unicorn, FPCW 0x077f",
              "coefficients": [[a, m.u32(a)] for a in coefficients], "rows": []}
    velocities = [(0, 0, 0), (1, .1, 0), (5, 0, 0), (10, 3, 0), (10, -3, 1),
                  (-10, 3, 0), (30, 15, 0), (60, -40, 5), (1, 20, 1)]
    for enabled in (0, 1):
        for hardcore in (0, 1):
            for velocity in velocities:
                inputs = [[0xBF6F06, enabled], [0xC06976, hardcore << 29], [0xBF6F2C, 0], [0xBF6F28, 0]]
                for address, value in inputs: m.w32(address, value)
                for i in range(6): m.w32(TABLE + 4 * i, OUT + 4 * i); m.w32(OUT + 4 * i, 0xDEADBEEF)
                for i, value in enumerate(velocity): m.wf(TABLE + 24 + 4 * i, value)
                m.call(0x561E50, TABLE)
                result["rows"].append({"enabled": enabled, "hardcore": hardcore, "velocity": list(velocity),
                    "inputs": inputs, "expected": [m.u32(OUT + 4 * i) for i in range(6)] + [m.u32(0xC086AC)]})
    out = ROOT / "tests/assists"
    (out / "stability_reference.json").write_text(json.dumps(result, indent=2) + "\n")
    (out / "stability_reference.luau").write_text("-- GENERATED by recovery/assist_implementation/stability_reference.py; original x86.\nreturn " + lua(result) + "\n")
    print(len(result["rows"]), "original stability force vectors")


if __name__ == "__main__": main()
