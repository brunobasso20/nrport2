"""Golden fixtures for the Stage 6/7 Luau tests, produced by the ORIGINAL NR2003.exe code in Unicorn.
  raw   : core only (inputs written straight to bf6360), flat plane, 1st..48th tick + every 36 ticks
  drive : driver layer (00551e80 port + original 005539c0 incl. 00553d70/rev limiter), every 36 ticks
Each scenario is also run from a 1-ulp perturbed initial state ('pert'): the spread between the
two original runs is the original's own sensitivity envelope used by the long-horizon tests."""
import sys, struct, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))  # recovery/stage6_7 tools
from orig_runtime import *
from gen_runtime import canonical_state, HOST

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else 'tests/stage67/fixtures')
JSON_OUT = Path(sys.argv[2] if len(sys.argv) > 2 else 'recovery/stage6_7/fixtures_json')
JSON_OUT.mkdir(parents=True, exist_ok=True)
OUT.mkdir(parents=True, exist_ok=True)

def ulp_up(x): return struct.unpack('<f', struct.pack('<I', struct.unpack('<I', struct.pack('<f', x))[0] + 1))[0]

def host(o):
    o.outF = [HOST + 0x00 + 16 * i for i in range(4)]; o.outP = [HOST + 0x40 + 16 * i for i in range(4)]
    o.gv = [HOST + 0x80 + 16 * i for i in range(4)]; o.blocks = [HOST + 0xc0 + 32 * i for i in range(4)]
    o.m.uc.mem_write(HOST, b'\0' * 0x200)

def raw_inputs(k):
    t = k / 288.0
    if t < 1.0: return dict(gear=1.0)
    if t < 4.0: return dict(gear=2.0, clutch=1.0, throttle=1.0)
    if t < 5.5: return dict(gear=2.0, clutch=1.0, throttle=0.6, lfSteer=0.04, rfSteer=0.035)
    return dict(gear=2.0, clutch=1.0, throttle=0.0, brake=0.7)

def drive_controls(frame):
    """36 Hz frame controls (frame 0 = ticks 1..8)"""
    t = frame / 36.0
    c = dict(throttle=0.0, brake=0.0, clutch=0.0, steer=0.0)
    if t >= 0.5: c['clutch'] = 1.0
    if t >= 0.75: c['throttle'] = 0.7
    if 4.5 <= t < 5.5: c['steer'] = 0.01
    if t >= 6.0: c['throttle'] = 0.0; c['brake'] = 0.5
    up = [round(36 * s) for s in (0.8, 1.6, 2.6, 3.8)]
    if frame in up: c['shiftUp'] = True
    if frame == round(36 * 6.6): c['shiftDown'] = True
    return c

def run(kind, perturb, N=2304, every=36, first=48):
    st = canonical_state()
    if perturb: st[4] = ulp_up(st[4])
    o = (OriginalDriver if kind == 'drive' else Original)(state=st); host(o); m = o.m
    con = flat(0.0, 1); rows = []
    for k in range(1, N + 1):
        if kind == 'drive':
            s = o.step_driver(drive_controls((k - 1) // 8), con)
        else:
            o.step(raw_inputs(k), con)
            S = HOST + 0x140; m.call(0x5b2cb0, S, o.root); s = [m.f32(S + 4 * i) for i in range(45)]
        if k <= first or k % every == 0:
            extra = [m.i32(0x74c97c), m.uc.mem_read(0xbf6f3c, 1)[0], m.f32(0xbf6368), m.f32(0xbf6370)] if kind == 'drive' else []
            rows.append([k] + s + extra)
    return rows

def lua_rows(rows):
    return '{\n' + ',\n'.join('{' + ','.join(repr(float(x)) if isinstance(x, float) else str(x) for x in r) + '}' for r in rows) + '\n}'

for kind in ('raw', 'drive'):
    orig = run(kind, False); pert = run(kind, True)
    body = ['-- GENERATED by recovery/stage6_7/gen_fixtures.py from the ORIGINAL NR2003.exe (Unicorn).',
            '-- rows: {tick, state[1..45]%s}' % (', gearIndex, limiterFlag, throttleIn, clutchIn' if kind == 'drive' else ''),
            'return {', 'kind=%r,' % kind, 'ticks=2304, every=36, first=48,']
    if kind == 'drive':
        frames = [drive_controls(f) for f in range(2304 // 8)]
        body.append('controls={' + ','.join('{%r,%r,%r,%r,%s,%s}' % (c['throttle'], c['brake'], c['clutch'], c['steer'],
                    'true' if c.get('shiftUp') else 'false', 'true' if c.get('shiftDown') else 'false') for c in frames) + '},')
    body.append('orig=' + lua_rows(orig) + ',')
    body.append('pert=' + lua_rows(pert) + ',')
    body.append('}')
    (OUT / ('%s_fixture.lua' % kind)).write_text('\n'.join(body) + '\n')
    js = {'kind': kind, 'orig': orig, 'pert': pert}
    if kind == 'drive': js['controls'] = [drive_controls(f) for f in range(2304 // 8)]
    (JSON_OUT / ('%s_fixture.json' % kind)).write_text(json.dumps(js))
    print(kind, 'rows', len(orig), 'final x orig %.4f pert %.4f' % (orig[-1][1], pert[-1][1]))
