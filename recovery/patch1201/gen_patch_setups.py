"""Apply only official 1.2.0.1 Watkins fast/qualify setup payloads.

Expected load results are independently generated by the ORIGINAL x86 decoder
00558830 and validator 00558da0, not by the Python field mapping or Luau loader.
Requires NR2003_MEM/UNICORN_PY as the other Stage 10 recovery tools do.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
ARCHIVE_SHA256 = "f69747db9865ec560d93b09201ff6c0f687987110aac1eb16947be5b019ca6f5"
SOURCES = {
    "fast": (116, "1b21a99a381f46336e26710dbeefb25939d428d2e29db1f6249f8075eba89f49"),
    "qualify": (119, "57238c6233b9733dbf1296096df47f6c052371e3a7509bd17b821da8564b651e"),
}


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + (str(k) if isinstance(k, int) else json.dumps(k)) + "]=" + lua(v)
                              for k, v in value.items()) + "}"
    if isinstance(value, (list, tuple)):
        return "{" + ",".join(map(lua, value)) + "}"
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def replace_profile(text, name, replacement):
    pattern = r"(?m)^\s*" + re.escape(name) + r"\s*=.*$"
    result, count = re.subn(pattern, lambda _: replacement, text)
    assert count == 1, f"expected exactly one {name} profile"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--streams", type=Path, required=True, help="verified Wise payload extraction directory")
    parser.add_argument("--archive", type=Path, required=True, help="supplied patch ZIP, for recorded provenance")
    args = parser.parse_args()
    assert hashlib.sha256(args.archive.read_bytes()).hexdigest() == ARCHIVE_SHA256, "unrecognized patch archive"
    module_spec = importlib.util.spec_from_file_location("setup_parser", ROOT / "tools/build_watkinsglen_setups.py")
    recover = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(recover)
    descriptors = set()
    for line in (ROOT / "core/NR2003Cup/NR2003CupSetupData.lua").read_text().splitlines():
        match = re.match(r"\[(\d+)\]=\{", line)
        if match and "toInternal=nil" not in line:
            descriptors.add(int(match[1]))
    sys.path.insert(0, str(ROOT / "recovery/stage10"))
    import orig_setup as original

    target = ROOT / "roblox/NR2003WatkinsGlenSetup.lua"
    previous_fixture = ROOT / "watkinsglen_implementation/handling/tests/setup_load_fixtures.lua"
    sources_path = ROOT / "watkinsglen_implementation/handling/setup_sources.json"
    sources = json.loads(sources_path.read_text())
    module, old_reference = target.read_text(), previous_fixture.read_text()
    unchanged_module = {name: re.search(r"(?m)^\s*" + name + r"\s*=.*$", module).group()
                        for name in ("easy", "jasper")}
    unchanged_expected = {name: re.search(r"(?m)^\s*" + name + r"\s*=.*$", old_reference).group()
                          for name in ("easy", "jasper")}
    fixture = {
        "archiveSHA256": ARCHIVE_SHA256,
        "installerSHA256": "20a0e4c6febe68ac7fb008f7af90a9d83b5efee32509bf4ff2fb0ed5254f6134",
        "referenceExecutableSHA256": "27e76919be6722bee0dcaddc92454fea338e99a97404df6220448314feb4500a",
        "validationFPCW": "0x027f",
        "profiles": {},
    }
    for name, (stream, expected_hash) in SOURCES.items():
        source = args.streams / f"{stream:04d}.bin"
        decoded = recover.recover(source, descriptors)
        assert decoded["sha256"] == expected_hash, f"unrecognized official {name} payload"
        raw = source.read_bytes()
        at = raw.index(b"DGTS")
        version, size = struct.unpack_from("<II", raw, at + 4)
        chunk = raw[at + 12:at + 12 + size]
        m = original.boot()
        original.prepare(m, chassis_type=4)
        m.fpcw = 0x027F
        packed = m.alloc(size, chunk)
        assert m.call(0x558830, 0, version, packed, size, ecx=original.GARAGE) == size
        assert m.call(0x558DA0, ecx=original.GARAGE)
        loaded = {i: m.u32(original.GARAGE + 4 * i) for i in range(71) if i != 37}
        values = ",".join("[%d]=0x%08x" % (i, value) for i, value in decoded["values"].items())
        line = "    %s = {file=%s,sha256=%s,items={%s}}," % (
            name, json.dumps(name + ".cup.sim"), json.dumps(expected_hash), values)
        module = replace_profile(module, name, line)
        sources[name] = dict(decoded, file=name + ".cup.sim", wiseStream=stream,
                             patchArchiveSHA256=ARCHIVE_SHA256)
        expected_line = name + "={" + ",".join("[%d]=0x%08x" % (i, v) for i, v in loaded.items()) + "},"
        old_reference = replace_profile(old_reference, name, expected_line)
        fixture["profiles"][name] = {
            "file": name + ".cup.sim", "wiseStream": stream, "fileSHA256": expected_hash,
            "setupVersion": version, "lastItem": decoded["lastItem"],
            "fields": list(decoded["values"]), "chunkBase64": base64.b64encode(chunk).decode(),
            "raw": decoded["values"], "loadedOriginal": loaded,
        }
        print(f"{name}: {len(decoded['values'])} official raw fields; {len(loaded)} original-x86 validated fields")
    for name in ("easy", "jasper"):
        assert re.search(r"(?m)^\s*" + name + r"\s*=.*$", module).group() == unchanged_module[name]
        assert re.search(r"(?m)^\s*" + name + r"\s*=.*$", old_reference).group() == unchanged_expected[name]
    module = module.replace(
        "-- Generated by tools/build_watkinsglen_setups.py from the supplied original .sim files.",
        "-- Official patch 1.2.0.1 fast/qualify: recovery/patch1201/gen_patch_setups.py; easy/jasper retained.")
    target.write_text(module)
    previous_fixture.write_text(old_reference)
    sources_path.write_text(json.dumps(sources, indent=2) + "\n")
    out = ROOT / "tests/patch1201"
    (out / "setup_reference.json").write_text(json.dumps(fixture, indent=2) + "\n")
    (out / "setup_reference.luau").write_text(
        "-- Official patch bytes + independent original-x86 setup decoder/validator results.\nreturn " + lua(fixture) + "\n")


if __name__ == "__main__":
    main()
