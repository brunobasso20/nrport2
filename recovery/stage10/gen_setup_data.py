"""Generate core/NR2003Cup/NR2003CupSetupData.lua from the ORIGINAL program: the 184 setup descriptors
(c05150: kind u16 + descriptor pointer; descriptor: display type u16, min, max, step, default, toInternal,
toDisplay), the converter constants they read, the CRT default setup (00557d20 under CW 0x027f) and the Cup
active setup after the default completion 00559950 (chassis type 2, series 0), plus the Stage 10 semantic map."""
import sys, struct, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import orig_setup as OS
import setup_semantics as SEM

# converter functions -> constants they read (addresses, all float32 in .rdata unless noted)
CONV_CONSTS = [0x6ea4a4, 0x6ed00c, 0x6ea4cc, 0x6ed7b4, 0x6ed7b8, 0x6ed798, 0x6ee330, 0x6ed794, 0x6ee334,
               0x6ed7bc, 0x6ee338, 0x6ee33c, 0x6ee340, 0x6ee344, 0x6ee348, 0x6ee34c, 0x6ed79c, 0x6ed7a4,
               0x6ed7ac, 0x6ee350, 0x6ea454, 0x6ee358, 0x6ee354, 0x6e97d8, 0x6ee364, 0x6ee360, 0x6ee35c,
               0x871a7c, 0x871ad4]   # 00871a7c: .data (CRT 0042312c); 00871ad4: mode read by 004247e0
CONV_NAMES = {0x423dc0: 'F_ID', 0x423dd0: 'I_ID', 0x423de0: 'PCT_TO_FRAC', 0x423e00: 'FRAC_TO_PCT',
              0x423e30: 'INT_TO_FLOAT', 0x423e40: 'FLOAT_TO_INT', 0x423e60: 'DEG_TO_RAD', 0x423e80: 'RAD_TO_DEG',
              0x423ea0: 'STAGGER_IN_TO_M', 0x423ec0: 'STAGGER_M_TO_IN', 0x423ee0: 'FSPRING_LBIN_TO_NM',
              0x423f00: 'FSPRING_NM_TO_LBIN', 0x423f30: 'RSPRING_LBIN_TO_NM', 0x423f50: 'RSPRING_NM_TO_LBIN',
              0x423f80: 'IN_TO_M', 0x423fa0: 'M_TO_IN', 0x423fc0: 'TOE_IN_TO_RAD', 0x423fe0: 'TOE_RAD_TO_IN',
              0x424000: 'LB_TO_KG', 0x424020: 'KG_TO_LB', 0x424050: 'GAL_TO_KG', 0x424070: 'KG_TO_GAL',
              0x4240a0: 'K_TO_C', 0x4240c0: 'LB_TO_KG', 0x4240e0: 'KG_TO_LB', 0x424110: 'LB_TO_KG',
              0x424130: 'KG_TO_LB', 0x424160: 'FARB_RATE_TO_SIZE', 0x4241a0: 'RARB_RATE_TO_SIZE',
              0x4241d0: 'SPOILER_DEG_TO_INT', 0x4241f0: 'SPOILER_INT_TO_DEG', 0: None}

def main(out):
    m = OS.boot()
    crt = [m.u32(OS.ACTIVE + 4 * i) for i in range(184)]
    OS.prepare(m)
    cup = [m.u32(OS.ACTIVE + 4 * i) for i in range(184)]
    garage = [m.u32(OS.GARAGE + 4 * i) for i in range(184)]
    tail = bytes(m.uc.mem_read(OS.ACTIVE + 4 * 184, 0xefd - 4 * 184))
    L = ['-- GENERATED by recovery/stage10/gen_setup_data.py from NR2003.exe (original x86, Unicorn); do not edit.',
         '-- NR2003 Cup setup descriptors (c05150), converter constants, default setups and the Stage 10 semantic map.',
         '-- Values are raw 32-bit patterns: float items are IEEE single bits, int items are two\'s complement.',
         'return {']
    L.append('consts = {%s},' % ','.join('[0x%x]=0x%08x' % (a, m.u32(a)) for a in CONV_CONSTS))
    L.append('items = {')
    for i in range(184):
        e = 0xc05150 + 6 * i
        kind = struct.unpack('<H', m.uc.mem_read(e, 2))[0]; d = m.u32(e + 2)
        sem = SEM.S[i]
        f = ['i=%d' % i, 'kind=%d' % kind, 'name="%s"' % sem['name'], 'unit="%s"' % sem['unit'].replace('"', "'"),
             'group="%s"' % sem['group'], 'status="%s"' % sem['status']]
        if d:
            t = struct.unpack('<H', m.uc.mem_read(d, 2))[0]
            ti, td = m.u32(d + 18), m.u32(d + 22)
            f += ['desc=0x%x' % d, 'type=%d' % t, 'min=0x%08x' % m.u32(d + 2), 'max=0x%08x' % m.u32(d + 6),
                  'step=0x%08x' % m.u32(d + 10), 'default=0x%08x' % m.u32(d + 14),
                  'toInternal=%s' % ('"%s"' % CONV_NAMES[ti] if ti else 'nil'), 'toInternalAddr=0x%x' % ti,
                  'toDisplay=%s' % ('"%s"' % CONV_NAMES[td] if td else 'nil'), 'toDisplayAddr=0x%x' % td]
        L.append('[%d]={%s},' % (i, ','.join(f)))
    L.append('},')
    L.append('crtDefault = {[0]=%s},' % ','.join('0x%08x' % v for v in crt))
    L.append('cupDefault = {[0]=%s},' % ','.join('0x%08x' % v for v in cup))
    L.append('cupGarageDefault = {[0]=%s},' % ','.join('0x%08x' % v for v in garage))
    L.append('chassisInfo = {0x%08x,0x%08x,0x%08x},' % tuple(m.u32(OS.ACTIVE + 0xef1 + 4 * k) for k in range(3)))
    L.append('}')
    Path(out).write_text('\n'.join(L) + '\n')
    print('written', out)

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent.parent / 'core' / 'NR2003Cup' / 'NR2003CupSetupData.lua'))
