"""Stage 10: regenerate the Stage 6/7 vehicle core (NR2003CupImage*, NR2003CupCore, NR2003CupJIT*) from the
ORIGINAL build with the GENERIC (setup-invariant) emitter decisions (generic_search.py -> generic_tables.pkl).

Why: NR2003 regenerates the vehicle callbacks at every car build and its emitter folds value-dependent
decisions (0057c8d0 x==0, 0057c900 x==1, 0057ca60 shared constant cells, 005b9970 literal dedup). The
Stage 6/7 translation is the DEFAULT-setup specialisation of that code: a garage setup that changes one
of those decisions (e.g. a camber of exactly 0, or a value that no longer equals another literal) needs
different code. The generic structure takes the no-fold outcome at every decision site whose outcome
varies between setups, so ONE translated callback set represents every setup and the setup values live
in memory cells written by the original build (NR2003CupBuild).
Everything else is recovery/stage6_7/gen_runtime.py unchanged (same translator, lifter, windows).
Only the translated callbacks are shipped (NR2003CupJITG1..n): the shipped image and NR2003CupJIT* stay the
ORIGINAL natural build of the default setup (exact Stage 6-9 behaviour); NR2003CupGarage switches to the
generic callbacks only for a setup whose own emitter outcome differs from the default's.
Usage: python gen_runtime10.py <out_dir> [<core_dir to receive NR2003CupJITG*.lua>]"""
import os, sys, pickle
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE.parent / 'stage6_7'))
import orig_runtime, gen_runtime
import orig_setup as OS
from emitter_control import TableControl, install

def main(out_dir):
    tables = pickle.load(open(HERE / 'generic_tables.pkl', 'rb'))['tables']
    def generic_build(m, chassis_type=OS.OV.CHASSIS_TYPE, series=OS.OV.CUP, log=print):
        spec = OS.prepare(m, chassis_type, series)
        tc = TableControl(m, *tables); install(m, tc)
        OS.apply(m, {})
        assert not tc.violations, tc.violations[:5]
        assert tc.fk == len(tables[0]) and tc.lk == len(tables[1])
        return spec, 0x727290
    orig_runtime.build = generic_build
    gen_runtime.OUT = Path(out_dir); gen_runtime.OUT.mkdir(parents=True, exist_ok=True)
    gen_runtime.main()
    out = Path(out_dir)
    for p in sorted(out.glob('NR2003CupJIT[0-9]*.lua')):
        k = p.stem[len('NR2003CupJIT'):]
        src = p.read_text()
        head = ('-- Stage 10 GENERIC (setup-invariant) callback structure, generated by recovery/stage10/gen_runtime10.py:\n'
                '-- the same original emitter run with the no-fold outcome at the setup-dependent decision sites.\n')
        lines = src.split('\n')
        assert lines[0] == '--!native' and lines[1] == '--!optimize 2'
        (out / ('NR2003CupJITG%s.lua' % k)).write_text('\n'.join(lines[:2]) + '\n' + head + '\n'.join(lines[2:]))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE / 'out_core'))
